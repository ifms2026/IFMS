CREATE TABLE IF NOT EXISTS bank_statement_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_account VARCHAR(50) NOT NULL,
    bank_reference VARCHAR(100) NOT NULL,
    booking_date DATE NOT NULL,
    direction VARCHAR(3) NOT NULL CHECK(direction IN ('IN','OUT')),
    amount NUMERIC(19,2) NOT NULL CHECK(amount>0),
    state VARCHAR(10) NOT NULL CHECK(state IN ('BOOKED','PENDING')),
    description TEXT,
    imported_by BIGINT NOT NULL REFERENCES users(id),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(bank_account,bank_reference)
);
CREATE TABLE IF NOT EXISTS bank_statement_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_line_id BIGINT NOT NULL UNIQUE REFERENCES bank_statement_lines(id),
    transaction_id BIGINT NOT NULL UNIQUE REFERENCES transactions(id),
    matched_by BIGINT NOT NULL REFERENCES users(id),
    matched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reason TEXT NOT NULL
);
CREATE TRIGGER trg_bank_statement_append_only BEFORE UPDATE OR DELETE ON bank_statement_lines
    FOR EACH ROW EXECUTE FUNCTION reject_accounting_journal_mutation();
CREATE TRIGGER trg_bank_match_append_only BEFORE UPDATE OR DELETE ON bank_statement_matches
    FOR EACH ROW EXECUTE FUNCTION reject_accounting_journal_mutation();
