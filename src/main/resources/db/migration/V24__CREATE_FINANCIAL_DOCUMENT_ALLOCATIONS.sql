CREATE TABLE IF NOT EXISTS financial_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_key VARCHAR(64) NOT NULL UNIQUE,
    issuer_code VARCHAR(100) NOT NULL,
    document_number VARCHAR(100) NOT NULL,
    document_date DATE NOT NULL,
    total_amount NUMERIC(19,2) NOT NULL CHECK(total_amount>0),
    first_file_id BIGINT NOT NULL REFERENCES file_storages(id),
    verified_by BIGINT NOT NULL REFERENCES users(id),
    verified_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS financial_document_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES financial_documents(id),
    request_id BIGINT NOT NULL REFERENCES requests(id),
    amount NUMERIC(19,2) NOT NULL,
    original_allocation_id BIGINT UNIQUE REFERENCES financial_document_allocations(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((original_allocation_id IS NULL AND amount>0) OR (original_allocation_id IS NOT NULL AND amount<0))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_document_request_allocation ON financial_document_allocations(document_id,request_id)
    WHERE original_allocation_id IS NULL;
CREATE TRIGGER trg_financial_documents_append_only BEFORE UPDATE OR DELETE ON financial_documents
    FOR EACH ROW EXECUTE FUNCTION reject_accounting_journal_mutation();
CREATE TRIGGER trg_document_allocations_append_only BEFORE UPDATE OR DELETE ON financial_document_allocations
    FOR EACH ROW EXECUTE FUNCTION reject_accounting_journal_mutation();
